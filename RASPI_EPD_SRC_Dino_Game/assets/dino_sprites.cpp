// ---------------------------------------------------------------------
//  Framebuffer / buffer de pantalla
// ---------------------------------------------------------------------

using Buffer = uint8_t[BUFFER_H][BUFFER_W];

// Pone en 0 todo el buffer.
void clearBuffer(Buffer buf) {
    std::memset(buf, 0, sizeof(uint8_t) * BUFFER_H * BUFFER_W);
}

// Dibuja (OR logico) un sprite de SPRITE_H x SPRITE_W sobre el buffer,
// ubicando su esquina superior izquierda en (x, y).
// Los pixeles fuera del buffer se descartan de forma segura.
void drawSprite(Buffer buf, const uint8_t sprite[SPRITE_H][SPRITE_W], int x, int y) {
    for (int row = 0; row < SPRITE_H; ++row) {
        int by = y + row;
        if (by < 0 || by >= BUFFER_H) continue;
        for (int col = 0; col < SPRITE_W; ++col) {
            int bx = x + col;
            if (bx < 0 || bx >= BUFFER_W) continue;
            if (sprite[row][col]) {
                buf[by][bx] = 1;
            }
        }
    }
}

// Dibuja una linea horizontal de "suelo" en el buffer.
void drawGround(Buffer buf, int y) {
    if (y < 0 || y >= BUFFER_H) return;
    for (int x = 0; x < BUFFER_W; ++x) buf[y][x] = 1;
}

// Imprime el buffer por consola: '#' = pixel encendido (1), '.' = apagado (0).
void printBuffer(const Buffer buf) {
    for (int y = 0; y < BUFFER_H; ++y) {
        for (int x = 0; x < BUFFER_W; ++x) {
            std::cout << (buf[y][x] ? '#' : '.');
        }
        std::cout << '\n';
    }
}

// ---------------------------------------------------------------------
//  Estados / movimientos del dino
// ---------------------------------------------------------------------

enum class DinoState {
    RUNNING,
    JUMPING,
    DUCKING
};

// Devuelve el puntero al frame de sprite correspondiente al estado del
// dino y al numero de frame de animacion (para alternar patas / alas).
const uint8_t (*getDinoFrame(DinoState state, int frameIndex))[SPRITE_W] {
    switch (state) {
        case DinoState::RUNNING:
            return (frameIndex % 2 == 0) ? dino_run1 : dino_run2;
        case DinoState::JUMPING:
            return dino_jump;
        case DinoState::DUCKING:
            return (frameIndex % 2 == 0) ? dino_duck1 : dino_duck2;
    }
    return dino_run1;
}

const uint8_t (*getBirdFrame(int frameIndex))[SPRITE_W] {
    return (frameIndex % 2 == 0) ? bird1 : bird2;
}

// ---------------------------------------------------------------------
//  Demo de animacion por consola
// ---------------------------------------------------------------------

int main() {
    Buffer buf;

    int dinoX = 4;
    int dinoBaseY = GROUND_Y - SPRITE_H;   // dino parado sobre el suelo
    int cloudX = 45;
    int birdX = 60;

    // Simulacion simple de salto: offset vertical que sube y baja.
    const int jumpOffsets[] = {0, -2, -5, -8, -9, -8, -5, -2, 0};
    const int totalJumpFrames = sizeof(jumpOffsets) / sizeof(jumpOffsets[0]);

    const int totalSteps = 30;

    for (int step = 0; step < totalSteps; ++step) {
        clearBuffer(buf);
        drawGround(buf, GROUND_Y);

        // Nube fija en el fondo (decorativa).
        drawSprite(buf, cloud1, cloudX, 2);

        // Ave con animacion de alas.
        drawSprite(buf, getBirdFrame(step), birdX, 8);

        // Estado del dino segun el ciclo de la demo:
        //  - primeros pasos: corriendo
        //  - luego: saltando
        //  - luego: agachado
        DinoState state;
        int dinoY = dinoBaseY;

        if (step < 10) {
            state = DinoState::RUNNING;
        } else if (step < 10 + totalJumpFrames) {
            state = DinoState::JUMPING;
            dinoY = dinoBaseY + jumpOffsets[step - 10];
        } else {
            state = DinoState::DUCKING;
            dinoY = dinoBaseY + (SPRITE_H - 20); // silueta agachada mas baja/ancha
        }

        drawSprite(buf, getDinoFrame(state, step), dinoX, dinoY);

        // Limpia pantalla (ANSI) y dibuja el frame actual.
        std::cout << "\x1B[2J\x1B[H";
        printBuffer(buf);
        std::cout << "Frame: " << step
                  << "  Estado: "
                  << (state == DinoState::RUNNING ? "CORRIENDO" :
                      state == DinoState::JUMPING  ? "SALTANDO"  : "AGACHADO")
                  << std::endl;

        std::this_thread::sleep_for(std::chrono::milliseconds(150));
    }

    return 0;
}
