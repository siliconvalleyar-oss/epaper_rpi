/*
 * dino_sprites.cpp
 * -----------------------------------------------------------------------
 * Sprites binarios (1 bit por pixel, 0 = fondo, 1 = pixel encendido)
 * para un juego estilo "Dino de Chrome".
 *
 * Cada sprite es una matriz de 32 filas x 32 columnas (SPRITE_H x SPRITE_W).
 * Contiene:
 *   - dino_run1 / dino_run2   -> animacion de correr (2 frames, piernas alternadas)
 *   - dino_jump                -> dino saltando (piernas juntas/recogidas)
 *   - dino_duck1 / dino_duck2 -> dino agachado (2 frames, silueta baja y ancha)
 *   - bird1 / bird2            -> ave prehistorica / pterodactilo (alas arriba/abajo)
 *   - cloud1                   -> nube
 *
 * Incluye una funcion generica drawSprite() que "pinta" (hace OR) un sprite
 * de 0/1 sobre un buffer de pantalla mas grande, en una posicion (x, y),
 * y una funcion printBuffer() para ver el resultado por consola (ASCII).
 *
 * Compilar:  g++ -std=c++17 -O2 dino_sprites.cpp -o dino_sprites
 * Ejecutar:  ./dino_sprites
 * -----------------------------------------------------------------------
 */

